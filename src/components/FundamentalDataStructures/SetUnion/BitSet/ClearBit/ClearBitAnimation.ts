import { LinearAnimation } from '../../../../../visualization/LinearAnimation.ts'
import { AnimationSequence } from '../../../../../visualization/AnimationSequence.ts'
import type { LinearInputValues, LinearModel } from '../../../../../visualization/LinearModel.ts'
import type { AlgorithmInformation } from '../../../../../visualization/AlgorithmInformation.ts'
import { BitSetLayout } from '../BitSetLayout.ts'

export class ClearBitAnimation extends LinearAnimation {
  public static readonly title = 'Clear a bit'
  public static readonly summary = 'Compute the packed-word index and AND the complemented mask.'

  public static describe(size: number): AlgorithmInformation {
    const information = AnimationSequence.information(this.title, this.summary, size,
      ['O(1)', 'O(1)', 'O(1)'], 'A fixed number of 32-bit operations accesses one existing packed word. The bit count never changes.',
      ['O(1)', 'O(1)', 'O(1)'], 'Only a fixed number of local variables are required.')
    return { ...information, terms: [
        { symbol: 'n', meaning: `Original logical size for this run: n = ${size}.` },
        { symbol: 'O(1)', meaning: 'Constant work or additional storage.' },
    ] }
  }

  constructor(model: LinearModel, input: LinearInputValues = {}) {
    super(model, new BitSetLayout(), 'clear-bit', input, ClearBitAnimation.title, ClearBitAnimation.summary)
  }
}
