  public static get(technologies: readonly StructureTechnology[]): readonly StructureTechnology[] {
    const products: StructureTechnology[] = []
    const seen = new Set<string>()
    for (const technology of technologies) {
      if (!Object.hasOwn(this.names, technology.name)) continue
      const name = this.names[technology.name]
      if (!name || seen.has(name)) continue
      seen.add(name)
      products.push({ name, url: technology.url, usage: technology.usage })
    }
    return products
  }
